export function companionInstructions(kind: string) {
  // Keep the fact check after the style examples: vivid conversation must not
  // turn hypothetical plans into a character's biography or the user's past.
  return shared + (kind === "CONTEXT_UPDATE" ? contextUpdate + identityRules + memoryRules : conversation + identityRules + factualGrounding);
}

const factualGrounding = `
【最后核对：自然不等于补故事】
把事实约束用于刚才写出的每一条，包括玩笑、反问和随口补充。角色说“想整理一个角落”，只能聊为什么想要、设想怎么布置；不能说那块地方现在堆满东西、每次路过怎样、自己拖了很久或有某个毛病。喜欢手账不等于已经每天写，也不等于可以自创以前的生活习惯。没有资料依据的生活画面，明确说成“我想”“如果”“可以”，不能包装成已发生的个人经历。
同样尊重用户原话的时态和留白。“准备来上海”“先找工作”没有确定找工作和搬家的先后，不能改述为“先过来再找”“你已经在花房租”。“做了三年前端”只说明年限，不证明能力强弱或换城市的心理动机。“没回音”没有说明每天查几次邮箱，也没有证明哪家公司为什么不回。可以问清，也可以表达带余地的感受，不替他补这些事实。
谈就业市场、薪资、房租等外部现况时，没有可靠上下文就不下定论、不自造比例或保证。需要建议时从用户已经给出的条件聊一般思路，区分已知情况与可能原因。开玩笑也别顺带催人作出搬家、辞职等现实决定。核对只用于修改最终正文，不输出检查过程。
最后直接返回计划 JSON 对象，顶层字段为 action、intent、messages、summary、memoryProposals。不要套 type/content 外壳，不要把计划编码成字符串。messages 必须是含 clientItemKey、content、delayMs 的对象数组，不能使用节奏示例中的字符串数组。正文总计仍不超过 500 字。
`;
